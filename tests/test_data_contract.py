@pytest.mark.parametrize("name", _case_ids(valid_only=True))
def test_valid_fixture_block_is_points_times_dimension_times_four(name: str) -> None:
    case = next(c for c in _cases() if c["name"] == name)
    data, block = _load(case["file"])
    assert block is not None
    expected = len(data["points"]) * data["dimension"] * 4
    assert len(block) == expected
    assert data["count"] == len(data["points"])
    assert data["vectors"]["byte_length"] == expected


# ---------------------------------------------------------------------------
# The reference validator agrees with every case, with one fault per refusal.
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("name", _case_ids())
def test_case_outcome_matches_the_index(name: str) -> None:
    index = _index()
    case = next(c for c in index["cases"] if c["name"] == name)
    base, base_block = _load(case["base"])
    if base is not None:
        assert validate(base, base_block, None, index["messages"]) == [], "base must be valid"
    data, block = _load(case["file"])
    faults = validate(data, block, base, index["messages"])
    if case["valid"]:
        assert faults == []
        expect = case["expect"]
        ids = ([p["id"] for p in base["points"]] if base else []) + [
            p["id"] for p in data["points"]
        ]
        assert expect["ids"] == ids
        assert expect["count"] == len(ids)
        effective = base or data
        assert expect["model"] == effective["model"]
        assert expect["dimension"] == effective["dimension"]
        assert expect["reduction"] == effective.get("reduction", {}).get("kind", "none")
        text = effective["text_included"] and data["text_included"]
        assert expect["text_included"] is text
        assert case["refusal"] is None
    else:
        assert "expect" not in case
        assert len(faults) == 1, f"{name} should have one clear reason, found {faults}"
        code, message = faults[0]
        assert case["refusal"] == {"code": code, "message": message}


def test_labels_only_fixture_carries_no_label_text_beyond_ids() -> None:
    for case in _cases():
        if not case["valid"]:
            continue
        data, _ = _load(case["file"])
        if data["text_included"]:
            continue
        for point in data["points"]:
            assert point["label"] == point["id"]
            assert point.get("metadata", {}) == {}


