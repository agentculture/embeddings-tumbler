"""Tests for the data contract (docs/data-contract.md) and its fixtures.

The fixtures under ``tests/fixtures/contract/`` are what the JavaScript loader
(task t5) is tested against, table-driven from ``index.json``. This file checks
three things the plan asks for, and one it implies:

1. Every fixture is generated by ``scripts/gen_contract_fixtures.py``, a
   stdlib-only script, and regenerating gives byte-identical files.
2. Each valid fixture's vector block is exactly points x dimension x 4 bytes.
3. The document names every field, refusal code and message template the
   fixtures use.
4. A small reference validator written here from the document agrees with the
   index on every case, and finds exactly one fault in each refused fixture,
   so each refusal fixture has one clear reason.
"""

from __future__ import annotations

import ast
import json
import math
import re
import struct
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
FIXTURES = REPO_ROOT / "tests" / "fixtures" / "contract"
GENERATOR = REPO_ROOT / "scripts" / "gen_contract_fixtures.py"
CONTRACT_DOC = REPO_ROOT / "docs" / "data-contract.md"

SUPPORTED_VERSIONS = [1]
KIND = "embeddings-tumbler/data"
FILE_NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
ADDRESS_RE = re.compile(r"://|localhost|[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+|:[0-9]+", re.IGNORECASE)
MAX_SAFE_INTEGER = 2**53 - 1


def _index() -> dict:
    return json.loads((FIXTURES / "index.json").read_text(encoding="utf-8"))


def _cases() -> list[dict]:
    return _index()["cases"]


def _case_ids(valid_only: bool = False) -> list[str]:
    try:
        return [case["name"] for case in _cases() if case["valid"] or not valid_only]
    except FileNotFoundError:
        return []


# ---------------------------------------------------------------------------
# A reference validator, written from docs/data-contract.md.
# It returns every fault it finds, in the document's check order; the viewer
# reports only the first. Collecting all of them lets the tests show that each
# refusal fixture has exactly one reason.
# ---------------------------------------------------------------------------


def _is_int(value: object) -> bool:
    if isinstance(value, bool):
        return False
    if isinstance(value, int):
        return abs(value) <= MAX_SAFE_INTEGER
    if isinstance(value, float):
        return math.isfinite(value) and value.is_integer() and abs(value) <= MAX_SAFE_INTEGER
    return False


def _is_number(value: object) -> bool:
    return (
        isinstance(value, (int, float))
        and not isinstance(value, bool)
        and math.isfinite(float(value))
    )


def _is_str(value: object, *, non_empty: bool = False) -> bool:
    return isinstance(value, str) and (bool(value) or not non_empty)


def _is_str_list(value: object) -> bool:
    return isinstance(value, list) and all(isinstance(item, str) for item in value)


class Faults:
    def __init__(self, templates: dict[str, str]) -> None:
        self.templates = templates
        self.items: list[tuple[str, str]] = []

    def add(self, code: str, **values: object) -> None:
        message = self.templates[code]
        for key, value in values.items():
            message = message.replace("{" + key + "}", str(value))
        assert "{" not in message, f"unfilled placeholder in {message!r}"
        self.items.append((code, message))


def _check_fields(data: dict, faults: Faults) -> None:  # noqa: C901 - mirrors the doc's table
    def bad(path: str) -> None:
        faults.add("invalid-field", field=path)

    op = data.get("op", "replace")
    if op not in ("replace", "append"):
        bad("op")
    if not _is_str(data.get("model"), non_empty=True):
        bad("model")
    if not (_is_int(data.get("dimension")) and data["dimension"] >= 1):
        bad("dimension")
    if not (_is_int(data.get("count")) and data["count"] >= 0):
        bad("count")
    if not isinstance(data.get("text_included"), bool):
        bad("text_included")

    if "provenance" in data or op != "append":
        prov = data.get("provenance")
        if not isinstance(prov, dict):
            bad("provenance")
        else:
            for key in ("source", "producer"):
                if not _is_str(prov.get(key), non_empty=True):
                    bad(f"provenance.{key}")
            if not isinstance(prov.get("synthetic"), bool):
                bad("provenance.synthetic")
            if "seed" not in prov or not (prov["seed"] is None or _is_int(prov["seed"])):
                bad("provenance.seed")
            for key in ("limitations", "uncertain"):
                if not _is_str_list(prov.get(key)):
                    bad(f"provenance.{key}")
            if "created" in prov and not _is_str(prov["created"]):
                bad("provenance.created")
            if "endpoint" in prov and not _is_str(prov["endpoint"], non_empty=True):
                bad("provenance.endpoint")
            if "params" in prov and not isinstance(prov["params"], dict):
                bad("provenance.params")

    if "reduction" in data:
        red = data["reduction"]
        if not isinstance(red, dict):
            bad("reduction")
        else:
            shape_ok = True
            if red.get("kind") not in ("none", "rotation", "top-k"):
                bad("reduction.kind")
                shape_ok = False
            for key in ("source_dimension", "directions_kept"):
                if not (_is_int(red.get(key)) and red[key] >= 1):
                    bad(f"reduction.{key}")
                    shape_ok = False
            vd = red.get("variance_dropped")
            if not (_is_number(vd) and 0 <= vd <= 1):
                bad("reduction.variance_dropped")
                shape_ok = False
            if shape_ok and _is_int(data.get("dimension")):
                dim = data["dimension"]
                consistent = red["directions_kept"] == dim
                if red["kind"] in ("none", "rotation"):
                    consistent = consistent and red["source_dimension"] == dim and vd == 0
                else:
                    consistent = consistent and dim < red["source_dimension"] and vd < 1
                if not consistent:
                    bad("reduction")

    vec = data.get("vectors")
    if not isinstance(vec, dict):
        bad("vectors")
    else:
        if not _is_str(vec.get("file"), non_empty=True):
            bad("vectors.file")
        if vec.get("dtype") != "float32":
            bad("vectors.dtype")
        if vec.get("byte_order") != "little":
            bad("vectors.byte_order")
        expected = None
        if _is_int(data.get("dimension")) and _is_int(data.get("count")):
            expected = data["count"] * data["dimension"] * 4
        if not (_is_int(vec.get("byte_length")) and vec["byte_length"] == expected):
            bad("vectors.byte_length")

    points = data.get("points")
    if not isinstance(points, list):
        bad("points")
    else:
        for i, point in enumerate(points):
            if not isinstance(point, dict):
                bad(f"points[{i}]")
                continue
            if not _is_str(point.get("id"), non_empty=True):
                bad(f"points[{i}].id")
            if not _is_str(point.get("label")):
                bad(f"points[{i}].label")
            if "group" in point and not _is_str(point["group"]):
                bad(f"points[{i}].group")
            if "metadata" in point and not isinstance(point["metadata"], dict):
                bad(f"points[{i}].metadata")


def validate(data: object, block: bytes | None, base: dict | None, templates: dict) -> list:
    """Return every fault in ``data`` (file form) in the contract's check order."""
    faults = Faults(templates)
    if not isinstance(data, dict) or data.get("kind") != KIND:
        faults.add("wrong-kind")
        return faults.items
    version = data.get("schema_version")
    if not (_is_int(version) and int(version) in SUPPORTED_VERSIONS):
        found = "missing" if "schema_version" not in data else json.dumps(version)
        supported = ", ".join(str(v) for v in SUPPORTED_VERSIONS)
        faults.add("schema-version", found=found, supported=supported)
        return faults.items

    _check_fields(data, faults)
    if faults.items:
        return faults.items

    vec_file = data["vectors"]["file"]
    readable = bool(FILE_NAME_RE.match(vec_file))
    if not readable:
        faults.add("vector-file-path", file=vec_file)
    endpoint = data.get("provenance", {}).get("endpoint")
    if endpoint is not None and ADDRESS_RE.search(endpoint):
        faults.add("endpoint-is-address")
    points = data["points"]
    if len(points) != data["count"]:
        faults.add("count-mismatch", count=data["count"], found=len(points))
    seen: set[str] = set()
    for point in points:
        if point["id"] in seen:
            faults.add("duplicate-id", id=point["id"])
        seen.add(point["id"])

    dim, count = data["dimension"], data["count"]
    expected = count * dim * 4
    if block is None:
        block = b""
    if not readable:
        pass  # a refused path is never read, so the block is not checked
    elif len(block) != expected:
        faults.add("block-length", found=len(block), count=count, dimension=dim, expected=expected)
    elif len(points) == count:
        values = struct.unpack(f"<{count * dim}f", block)
        for i in range(count):
            row = values[i * dim : (i + 1) * dim]
            if not all(math.isfinite(v) for v in row):
                faults.add("non-finite", id=points[i]["id"])

    if data.get("op", "replace") == "append":
        if base is None:
            faults.add("append-without-base")
        else:
            if data["model"] != base["model"]:
                faults.add("model-mismatch", found=data["model"], expected=base["model"])
            if dim != base["dimension"]:
                faults.add("dimension-mismatch", found=dim, expected=base["dimension"])
            mine = data.get("reduction", {}).get("kind", "none")
            theirs = base.get("reduction", {}).get("kind", "none")
            if mine != theirs:
                faults.add("reduction-mismatch", found=mine, expected=theirs)
            existing = {p["id"] for p in base["points"]}
            for point in points:
                if point["id"] in existing:
                    faults.add("id-exists", id=point["id"])
    return faults.items


def _load(name: str | None) -> tuple[dict | None, bytes | None]:
    if name is None:
        return None, None
    data = json.loads((FIXTURES / name).read_text(encoding="utf-8"))
    block = None
    vec = data.get("vectors") if isinstance(data, dict) else None
    if isinstance(vec, dict) and isinstance(vec.get("file"), str):
        path = FIXTURES / vec["file"]
        if FILE_NAME_RE.match(vec["file"]) and path.is_file():
            block = path.read_bytes()
    return data, block


# ---------------------------------------------------------------------------
# Generator: present, stdlib-only, deterministic, and the source of every file.
# ---------------------------------------------------------------------------


def test_generator_is_stdlib_only() -> None:
    tree = ast.parse(GENERATOR.read_text(encoding="utf-8"))
    modules: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            modules.update(alias.name.split(".")[0] for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
            modules.add(node.module.split(".")[0])
    non_stdlib = sorted(m for m in modules if m not in sys.stdlib_module_names)
    assert non_stdlib == [], f"generator imports non-stdlib modules: {non_stdlib}"


def test_regenerating_gives_byte_identical_fixtures(tmp_path: Path) -> None:
    result = subprocess.run(
        [sys.executable, "-I", str(GENERATOR), "--out", str(tmp_path)],
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stderr
    fresh = sorted(p.name for p in tmp_path.iterdir())
    committed = sorted(p.name for p in FIXTURES.iterdir())
    assert fresh == committed, "the committed fixture set differs from a fresh generation"
    for name in fresh:
        assert (tmp_path / name).read_bytes() == (FIXTURES / name).read_bytes(), name


def test_two_generations_are_identical(tmp_path: Path) -> None:
    for sub in ("a", "b"):
        subprocess.run(
            [sys.executable, "-I", str(GENERATOR), "--out", str(tmp_path / sub)],
            check=True,
            capture_output=True,
        )
    names = sorted(p.name for p in (tmp_path / "a").iterdir())
    assert names == sorted(p.name for p in (tmp_path / "b").iterdir())
    for name in names:
        assert (tmp_path / "a" / name).read_bytes() == (tmp_path / "b" / name).read_bytes()


