def test_document_names_every_field_and_rule() -> None:
    doc = CONTRACT_DOC.read_text(encoding="utf-8")
    fields = [
        "schema_version",
        "kind",
        "op",
        "model",
        "dimension",
        "count",
        "text_included",
        "provenance",
        "source",
        "producer",
        "synthetic",
        "seed",
        "limitations",
        "uncertain",
        "created",
        "endpoint",
        "params",
        "reduction",
        "source_dimension",
        "directions_kept",
        "variance_dropped",
        "vectors",
        "file",
        "dtype",
        "byte_order",
        "byte_length",
        "points",
        "id",
        "label",
        "group",
        "metadata",
    ]
    for name in fields:
        assert f"`{name}`" in doc, f"field {name} is not documented"
    for word in ("little-endian", "float32", "count × dimension × 4", "Float32Array"):
        assert word in doc, word
    for op in ("`replace`", "`append`"):
        assert op in doc


def test_document_lists_every_refusal_code_and_message_template() -> None:
    doc = CONTRACT_DOC.read_text(encoding="utf-8")
    for code, template in _index()["messages"].items():
        assert f"`{code}`" in doc, f"refusal code {code} is not documented"
        assert template in doc, f"message template for {code} is not in the document"
