def test_index_references_every_fixture_file_and_nothing_else() -> None:
    referenced = {"index.json"}
    for case in _cases():
        for name in (case["file"], case["base"]):
            if name is None:
                continue
            referenced.add(name)
            data, _ = _load(name)
            vec_file = data.get("vectors", {}).get("file")
            if isinstance(vec_file, str) and FILE_NAME_RE.match(vec_file):
                referenced.add(vec_file)
    on_disk = {p.name for p in FIXTURES.iterdir()}
    assert referenced == on_disk


def test_index_covers_the_cases_the_plan_names() -> None:
    cases = {case["name"]: case for case in _cases()}
    dims = {}
    for case in cases.values():
        if case["valid"]:
            data, _ = _load(case["file"])
            dims.setdefault(data["dimension"], []).append(case["name"])
    assert 384 in dims and 1024 in dims, "valid 384-d and 1024-d sets are required"
    labels_only = [
        c for c in cases.values() if c["valid"] and _load(c["file"])[0]["text_included"] is False
    ]
    assert labels_only, "a labels-only set is required"
    codes = {c["refusal"]["code"] for c in cases.values() if not c["valid"]}
    for needed in ("schema-version", "block-length", "dimension-mismatch", "model-mismatch"):
        assert needed in codes, f"no fixture is refused with {needed}"


def test_every_refusal_code_has_a_fixture() -> None:
    codes = {c["refusal"]["code"] for c in _cases() if not c["valid"]}
    assert codes == set(_index()["messages"])


def test_bumped_version_message_names_both_versions() -> None:
    case = next(c for c in _cases() if c["refusal"] and c["refusal"]["code"] == "schema-version")
    data, _ = _load(case["file"])
    message = case["refusal"]["message"]
    assert str(data["schema_version"]) in message
    assert "1" in message.replace(str(data["schema_version"]), "")


