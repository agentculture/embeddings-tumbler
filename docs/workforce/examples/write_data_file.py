"""Illustrative producer: write a viewer data file with the standard library only.

A sketch from planning, not the contract. Task t2 writes the authoritative
contract in docs/data-contract.md; if the two disagree, the contract wins.

The file has two parts, written side by side:

* ``<name>.json``  — version, provenance and one record per point.
* ``<name>.f32``   — every vector as little-endian float32, row after row, so
  its length is exactly ``count * dimension * 4`` bytes.

Run:  python3 write_data_file.py out_dir
"""

from __future__ import annotations

import json
import random
import struct
import sys
from pathlib import Path

SCHEMA_VERSION = 1


def write_data_file(
    out_dir: Path,
    name: str,
    *,
    model: str,
    points: list[dict],
    vectors: list[list[float]],
    source: str,
    synthetic: bool,
    include_text: bool = True,
) -> Path:
    """Write ``<name>.json`` and ``<name>.f32``; return the JSON path."""
    if len(points) != len(vectors):
        raise ValueError("one vector per point is required")
    dimension = len(vectors[0])
    if any(len(v) != dimension for v in vectors):
        raise ValueError("every vector must have the same dimension")

    block = b"".join(struct.pack(f"<{dimension}f", *v) for v in vectors)
    records = []
    for point in points:
        record = {"id": point["id"], "group": point.get("group", "")}
        # A labels-only file leaves the corpus text out: vectors can leak the
        # text they were made from, so including text is a choice.
        record["label"] = point.get("label", "") if include_text else point["id"]
        record["metadata"] = point.get("metadata", {}) if include_text else {}
        records.append(record)

    manifest = {
        "schema_version": SCHEMA_VERSION,
        "kind": "embeddings-tumbler/data",
        "model": model,
        "dimension": dimension,
        "count": len(points),
        "provenance": {
            "source": source,
            "producer": "write_data_file.py (example)",
            "synthetic": synthetic,
            "limitations": [],
            "uncertain": [],
        },
        "reduction": {"kind": "none", "directions_kept": dimension, "variance_dropped": 0.0},
        "text_included": include_text,
        "vectors": {
            "file": f"{name}.f32",
            "dtype": "float32",
            "byte_order": "little",
            "byte_length": len(block),
        },
        "points": records,
    }
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / f"{name}.f32").write_bytes(block)
    target = out_dir / f"{name}.json"
    target.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return target


def main() -> int:
    out_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("out")
    rng = random.Random(0)
    dimension = 16
    points = [{"id": f"p{i}", "label": f"point {i}", "group": "demo"} for i in range(8)]
    vectors = [[rng.gauss(0.0, 1.0) for _ in range(dimension)] for _ in points]
    path = write_data_file(
        out_dir,
        "example",
        model="example/random-16",
        points=points,
        vectors=vectors,
        source="generated by write_data_file.py",
        synthetic=True,
    )
    print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
